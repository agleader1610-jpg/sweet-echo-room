
-- Per-game deposit rule columns on app_config (0 = disabled)
ALTER TABLE public.app_config
  ADD COLUMN IF NOT EXISTS aviator_lifetime_min_deposits    INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS aviator_recency_days             INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS aviator_recency_min_deposits     INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS wingo_lifetime_min_deposits      INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS wingo_recency_days               INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS wingo_recency_min_deposits       INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS wingo_auto_lifetime_min_deposits INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS wingo_auto_recency_days          INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS wingo_auto_recency_min_deposits  INTEGER NOT NULL DEFAULT 1;

-- Seed defaults from legacy global_deposit_days_required so existing behavior is preserved
UPDATE public.app_config
SET aviator_recency_days    = COALESCE(NULLIF(aviator_recency_days,0),    global_deposit_days_required),
    wingo_recency_days      = COALESCE(NULLIF(wingo_recency_days,0),      global_deposit_days_required),
    wingo_auto_recency_days = COALESCE(NULLIF(wingo_auto_recency_days,0), global_deposit_days_required)
WHERE id = 1;

-- Per-UID override: add game scope. NULL = applies to all games.
ALTER TABLE public.user_deposit_rules
  ADD COLUMN IF NOT EXISTS game TEXT,
  ADD COLUMN IF NOT EXISTS lifetime_min_deposits INTEGER,
  ADD COLUMN IF NOT EXISTS recency_days          INTEGER,
  ADD COLUMN IF NOT EXISTS recency_min_deposits  INTEGER;

-- Replace old PK/unique on uid with (uid, game) uniqueness (NULLs treated distinct = ok for "all-games" row)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'user_deposit_rules_pkey') THEN
    ALTER TABLE public.user_deposit_rules DROP CONSTRAINT user_deposit_rules_pkey;
  END IF;
END $$;

ALTER TABLE public.user_deposit_rules
  ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;

CREATE UNIQUE INDEX IF NOT EXISTS user_deposit_rules_uid_game_uniq
  ON public.user_deposit_rules (uid, COALESCE(game, '*'));

-- Log which game was checked
ALTER TABLE public.deposit_gate_log
  ADD COLUMN IF NOT EXISTS game TEXT,
  ADD COLUMN IF NOT EXISTS lifetime_count INTEGER,
  ADD COLUMN IF NOT EXISTS recent_count   INTEGER;
